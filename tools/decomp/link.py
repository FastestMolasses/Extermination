#!/usr/bin/env python3
"""Link the Extermination boot ELF from filler + matched objects via mwldmips.

This script:
  1. (Optionally) runs fill_unmatched.py to ensure build/filler/ is current.
  2. Generates config/SCUS_971.12.lcf with the exact per-function link order
     derived from vram addresses in the splat .s files.
  3. Generates build/link_objects.txt with the path to each .o file
     (mwldmips accepts @file to read a list of objects).
  4. Invokes mwldmips.exe via qemu-i386 + wibo32 inside the container.
  5. Compares the loadable region of the output ELF against the original.

Run this INSIDE the exterm-toolchain container (repo at /work), or via:
    container run --rm -v "$PWD:/work" -w /work exterm-toolchain \\
        python3 tools/decomp/link.py [--no-fill] [--dry-run]

Flags:
  --no-fill       skip fill_unmatched.py (use existing build/filler/)
  --dry-run       generate LCF + object list but don't invoke mwldmips
  --verify        compare linked ELF loadable bytes vs original (default on)
  --no-verify     skip byte comparison
"""
from __future__ import annotations

