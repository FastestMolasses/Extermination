def _load_abs_syms() -> str:
    """Load absolute-address symbols from splat auto files for inclusion in the LCF.

    Reads build/undefined_syms_auto.txt and build/undefined_funcs_auto.txt, plus
    hard-codes a few EE exception-vector addresses that splat doesn't know about.

    Also auto-derives addresses for any symbol whose name encodes its address in
    the pattern D_XXXXXXXX or func_XXXXXXXX (hex suffix = vram address).  This
    handles data-table references that splat named with a D_ prefix and function
    references to addresses outside the boot ELF (EE kernel entry vectors, IOP RAM,
    overlay addresses).

    Returns a block of '\tNAME = 0xADDR;\n' lines for insertion into SECTIONS.
    """
    import re as _re

    syms: dict[str, str] = {}

    # Hard-code EE exception/interrupt vector entry points.
    for name, addr in [
        ("func_00000008", "0x00000008"),
        ("func_0000000C", "0x0000000C"),
        ("func_00000010", "0x00000010"),
        ("func_00000014", "0x00000014"),
        ("func_0000001C", "0x0000001C"),
        ("func_00000804", "0x00000804"),
        ("func_0C000004", "0x0C000004"),
    ]:
        syms[name] = addr

    # Load splat's auto-generated undefined-symbol files.
    for auto_path in (
        BUILD / "undefined_syms_auto.txt",
        BUILD / "undefined_funcs_auto.txt",
    ):
        if not auto_path.exists():
            continue
        for line in auto_path.read_text().splitlines():
            m = _re.match(r"^(\S+)\s*=\s*(0x[0-9A-Fa-f]+);", line)
            if m:
                syms[m.group(1)] = m.group(2)

    # Auto-derive any D_XXXXXXXX or func_XXXXXXXX symbol whose address is encoded
    # in the name itself.  This covers symbols that appear as link-time references
    # but are absent from the auto files (often because they were "defined" by a
    # function that was renamed by splat, e.g. a data table named func_00230800).
    # We add ALL such deducible symbols rather than just the ones that errored,
    # because the set may change as more functions are matched.
    _name_re = _re.compile(r"^(?:D_|func_)([0-9A-Fa-f]{4,8})$")
    for auto_path in (
        BUILD / "undefined_syms_auto.txt",
        BUILD / "undefined_funcs_auto.txt",
    ):
        if not auto_path.exists():
            continue
        for line in auto_path.read_text().splitlines():
            m = _name_re.match(line.split()[0]) if line.split() else None
            if m:
                name = line.split()[0]
                addr = "0x{:08X}".format(int(m.group(1), 16))
                if name not in syms:
                    syms[name] = addr

    # Scan ALL .s files for D_XXXXXXXX and low-address func_XXXXXXXX references.
    # Any symbol whose name encodes its address can be provided as an absolute
    # definition — this covers thousands of BSS, IOP, hardware-register, and
    # data-table references that are absent from the auto files.
    _d_re = _re.compile(r"\bD_([0-9A-Fa-f]{7,8})\b")
    _f_re = _re.compile(r"\bfunc_([0-9A-Fa-f]{7,8})\b")
    for asm_file in ASM_DIR.glob("*.s"):
        content = asm_file.read_text(errors="replace")
        for m in _d_re.finditer(content):
            name = m.group(0)
            if name not in syms:
                syms[name] = "0x{:08X}".format(int(m.group(1), 16))
        for m in _f_re.finditer(content):
            name = m.group(0)
            addr = int(m.group(1), 16)
            # Only add func_ symbols that are OUTSIDE the boot ELF range —
            # those inside will be provided by the linked .o files.
            if addr < 0x00100000 or addr > 0x00275B00:
                if name not in syms:
                    syms[name] = "0x{:08X}".format(addr)

    if not syms:
        return ""
    lines = [f"\t{name} = {addr};\n" for name, addr in sorted(syms.items())]
    return "".join(lines)


def generate_lcf(funcs: list[str]) -> str:
    """Generate the full LCF content."""
    # LCF_HEADER uses {{/}} to escape braces for .format(); LCF_MIDDLE uses
    # single braces and is appended after a simple replace to avoid double-
    # brace confusion.
    abs_syms = _load_abs_syms()
    header = LCF_HEADER.format(n_funcs=len(funcs), abs_syms=abs_syms)
    # LCF_MIDDLE was written with {{ }} so it can share a .format() call;
    # normalize it here so the output has literal single-brace LCF syntax.
    middle = LCF_MIDDLE.replace("{{", "{").replace("}}", "}")
    obj_lines = "".join(f"\t\t{name}.o (.text)\n" for name in funcs)
    return header + obj_lines + "\n" + middle


# ---------------------------------------------------------------------------
# ELF comparison
# ---------------------------------------------------------------------------

def find_load_segment(elf_path: Path) -> tuple[int, int, int]:
    """Return (file_offset, vaddr, filesz) of the first PT_LOAD segment."""
    data = elf_path.read_bytes()
    # ELF32 little-endian header
    e_phoff = struct.unpack_from("<I", data, 0x1c)[0]
    e_phentsize = struct.unpack_from("<H", data, 0x2a)[0]
    e_phnum = struct.unpack_from("<H", data, 0x2c)[0]
    PT_LOAD = 1
    for i in range(e_phnum):
        off = e_phoff + i * e_phentsize
        p_type = struct.unpack_from("<I", data, off)[0]
        if p_type == PT_LOAD:
            p_offset = struct.unpack_from("<I", data, off + 4)[0]
            p_vaddr = struct.unpack_from("<I", data, off + 8)[0]
            p_filesz = struct.unpack_from("<I", data, off + 16)[0]
            return p_offset, p_vaddr, p_filesz
    raise ValueError(f"No PT_LOAD segment found in {elf_path}")


def compare_elf(linked: Path, original: Path) -> bool:
    """Compare the loadable content of linked vs original.  Return True if identical."""
    if not original.exists():
        print("[verify] original ELF not found — skip comparison")
        return True

    try:
        link_off, link_vaddr, link_filesz = find_load_segment(linked)
        orig_off, orig_vaddr, orig_filesz = find_load_segment(original)
    except (ValueError, struct.error) as e:
        print(f"[verify] could not parse ELF headers: {e}")
        return False

    print(f"[verify] linked  LOAD: offset=0x{link_off:x}, vaddr=0x{link_vaddr:x}, filesz=0x{link_filesz:x}")
    print(f"[verify] original LOAD: offset=0x{orig_off:x}, vaddr=0x{orig_vaddr:x}, filesz=0x{orig_filesz:x}")

    link_data = linked.read_bytes()
    orig_data = original.read_bytes()

    compare_size = min(link_filesz, orig_filesz)
    link_content = link_data[link_off: link_off + compare_size]
    orig_content = orig_data[orig_off: orig_off + compare_size]

    if link_content == orig_content:
        print(f"[verify] PASS — 0x{compare_size:x} loadable bytes are identical")
        if link_filesz != orig_filesz:
            print(f"[verify] NOTE: filesz differs (linked 0x{link_filesz:x} vs orig 0x{orig_filesz:x})")
        return True
    else:
        diffs = sum(1 for a, b in zip(link_content, orig_content) if a != b)
        print(f"[verify] FAIL — {diffs} byte(s) differ in 0x{compare_size:x}-byte loadable region")
        # Show first difference
        for i, (a, b) in enumerate(zip(link_content, orig_content)):
            if a != b:
                vram = (orig_vaddr + i) if orig_vaddr else i
                print(f"[verify]   first diff at 0x{vram:08x}: linked=0x{a:02x} orig=0x{b:02x}")
                break
        return False


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description="Link the Extermination boot ELF via mwldmips")
    ap.add_argument("--no-fill", action="store_true",
                    help="skip fill_unmatched.py (use existing build/filler/)")
    ap.add_argument("--dry-run", action="store_true",
                    help="generate LCF + object list but don't invoke mwldmips")
    ap.add_argument("--no-verify", action="store_true",
                    help="skip comparison against original ELF")
    args = ap.parse_args(argv)

    # Step 1: fill unmatched
    if not args.no_fill:
        print("[link] running fill_unmatched.py ...")
        r = subprocess.run(
            [sys.executable,
             str(ROOT / "tools" / "decomp" / "fill_unmatched.py"),
             "--jobs", "8"],
            cwd=ROOT,
        )
        if r.returncode != 0:
            print("[link] fill_unmatched.py failed", file=sys.stderr)
            return 1

    # Step 2: generate LCF
    funcs = sorted_functions()
    print(f"[link] {len(funcs)} functions in link order")
    lcf_text = generate_lcf(funcs)
    LCF.write_text(lcf_text)
    print(f"[link] wrote {LCF.relative_to(ROOT)}")

    # Step 3: generate object list
    missing = []
    obj_paths = []
    for name in funcs:
        obj = FILLER_DIR / f"{name}.o"
        if not obj.exists():
            missing.append(name)
        obj_paths.append(str(obj.relative_to(ROOT)))

    if missing:
        print(f"[link] WARNING: {len(missing)} objects missing from build/filler/:",
              file=sys.stderr)
        for m in missing[:10]:
            print(f"  {m}", file=sys.stderr)
        if len(missing) > 10:
            print(f"  ... and {len(missing) - 10} more", file=sys.stderr)

    OBJ_LIST.write_text("\n".join(obj_paths) + "\n")
    print(f"[link] wrote {OBJ_LIST.relative_to(ROOT)} ({len(obj_paths)} entries)")

    if args.dry_run:
        print("[link] dry-run: stopping before mwldmips invocation")
        return 0

    # Step 4: link
    (ROOT / "elf").mkdir(exist_ok=True)
    cmd = (MWLD + [
        "-map",
        "-nostdlib",
        "-m", "_start",
        "-nodead",
        "-o", str(ELF_OUT.relative_to(ROOT)),
        str(LCF.relative_to(ROOT)),
        f"@{OBJ_LIST.relative_to(ROOT)}",
    ])
    print(f"[link] invoking mwldmips: {' '.join(cmd)}")
    result = subprocess.run(cmd, cwd=ROOT)
    if result.returncode != 0:
        print(f"[link] mwldmips failed (exit {result.returncode})", file=sys.stderr)
        # Still try verify if output exists
        if not ELF_OUT.exists():
            return 1
    else:
        print(f"[link] mwldmips succeeded → {ELF_OUT.relative_to(ROOT)}")

    # Step 5: verify
    if not args.no_verify:
        ok = compare_elf(ELF_OUT, ORIG_ELF)
        return 0 if ok else 2

    return result.returncode


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
